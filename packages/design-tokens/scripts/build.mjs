// Generates tokens.css from tokens.json. Run: node packages/design-tokens/scripts/build.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { kebab, resolveValue, root, semanticLeaves, tokens } from './lib.mjs';

const decl = (name, value) => `  --${name}: ${String(value).toLowerCase()};`;
const legacy = tokens.color;

const light = [
  '  /* Legacy names (web-admin, category palette). */',
  ...['brand', 'neutral', 'semantic'].flatMap((group) =>
    Object.entries(legacy[group]).map(([key, hex]) => decl(`color-${group}-${kebab(key)}`, hex))),
  `  --gradient-cta: linear-gradient(90deg, ${legacy.gradient.ctaStart.toLowerCase()}, ${legacy.gradient.ctaEnd.toLowerCase()});`,
  '',
  '  /* Semantic colours. */',
  ...semanticLeaves().map(([path, value]) => decl(`color-${path.map(kebab).join('-')}`, resolveValue(value, 'light'))),
  '',
  '  /* Scales. */',
  `  --font-family: '${tokens.typography.fontFamily}', system-ui, sans-serif;`,
  ...Object.entries(tokens.space).map(([k, v]) => `  --space-${k}: ${v}px;`),
  ...Object.entries(tokens.radius).map(([k, v]) => `  --radius-${kebab(k)}: ${v}px;`),
  ...['1', '2'].map((k) => `  --elevation-${k}: ${tokens.elevation[k].map((s) => `${s.x}px ${s.y}px ${s.blur}px ${s.color.toLowerCase()}`).join(', ')};`),
  ...Object.entries(tokens.motion.duration).map(([k, v]) => `  --duration-${kebab(k)}: ${v}ms;`),
  `  --easing-standard: cubic-bezier(${tokens.motion.easing.standard.join(', ')});`,
];

const dark = [
  ...Object.entries(legacy.dark).map(([key, hex]) => decl(`color-neutral-${kebab(key)}`, hex)),
  ...semanticLeaves().map(([path, value]) => decl(`color-${path.map(kebab).join('-')}`, resolveValue(value, 'dark'))),
];

const css = `/* Generated by scripts/build.mjs from tokens.json. Do not edit by hand. */
:root {
${light.join('\n')}
}

[data-theme='dark'] {
${dark.join('\n')}
}
`;

const out = resolve(root, 'tokens.css');
if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== css) {
    console.error('tokens.css is stale. Run: node packages/design-tokens/scripts/build.mjs');
    process.exit(1);
  }
  console.log('tokens.css is up to date.');
} else {
  writeFileSync(out, css);
  console.log(`Wrote ${out}`);
}
