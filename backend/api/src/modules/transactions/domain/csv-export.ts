/** Hard cap so one request cannot load an unbounded ledger; the caller narrows the date range instead. */
export const CSV_EXPORT_MAX_ROWS = 50_000;
export const CSV_BOM = '﻿';
export const CSV_COLUMNS = ['date', 'time', 'type', 'amount', 'currency', 'wallet', 'category', 'merchant', 'notes', 'tags', 'transaction_id'] as const;

export interface CsvTransactionRow {
  id: string;
  occurredOn: string;
  occurredTime: string | null;
  type: string;
  amountMinor: bigint;
  currencyCode: string;
  minorDigits: number;
  walletName: string | null;
  categoryName: string | null;
  merchant: string | null;
  notes: string | null;
  tagNames: string[];
}

/** Signed plain decimal from minor units (`-12500` with 2 digits → `-125.00`); bigint math, no locale, no float. */
export function formatMinorAmount(amountMinor: bigint, minorDigits: number): string {
  const negative = amountMinor < 0n;
  const digits = (negative ? -amountMinor : amountMinor).toString().padStart(minorDigits + 1, '0');
  const whole = digits.slice(0, digits.length - minorDigits);
  const fraction = minorDigits ? `.${digits.slice(digits.length - minorDigits)}` : '';
  return `${negative ? '-' : ''}${whole}${fraction}`;
}

/**
 * RFC 4180 quoting. Text cells starting with `= + - @` (or tab/CR) get a leading `'` so Excel never runs them as formulas.
 * `;` is quoted too: Excel in vi-VN and other comma-decimal locales splits on `;`, which would turn the text after it
 * into its own unescaped cell (SEC-P6-002).
 */
export function csvText(value: string | null): string {
  if (!value) return '';
  const safe = /^[=+\-@\t\r]/.test(value) ? `'${value}` : value;
  return /[",;\r\n]/.test(safe) ? `"${safe.replace(/"/g, '""')}"` : safe;
}

export function buildTransactionsCsv(rows: CsvTransactionRow[]): string {
  // Date, time, type, amount, currency and id are generated by us (no user text), so only the free-text cells are escaped.
  const lines = rows.map(row => [
    row.occurredOn, row.occurredTime ?? '', row.type, formatMinorAmount(row.amountMinor, row.minorDigits), row.currencyCode,
    csvText(row.walletName), csvText(row.categoryName), csvText(row.merchant), csvText(row.notes), csvText(row.tagNames.join(';')), row.id,
  ].join(','));
  return `${CSV_BOM}${[CSV_COLUMNS.join(','), ...lines].join('\r\n')}\r\n`;
}
